    private void BtnAdicionar_ITEMActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnAdicionar_ITEMActionPerformed

String nome = TxtProduto.getText().trim(); // Remove espaços extras
Produtos obj = new Produtos();
ProdutosDAO daop = new ProdutosDAO();

// Busca o produto no banco de dados
obj = daop.BuscarProduto(nome);

if (obj != null && obj.getNome() != null) {
    try {
        // Converte os valores dos campos
        int estoque = Integer.parseInt(TxtEstoque.getText().trim());
        int quantidade = Integer.parseInt(TxtQuantidade.getText().trim());
        
        // Substitui vírgulas por pontos antes de converter para Double
        String precoTexto = TxtPreço.getText().trim().replace(",", ".");
        preco = Double.parseDouble(precoTexto);
        
        qnt = quantidade;

        // Calcula subtotal e total
        subtotal = preco * qnt;
        total += subtotal;

        // Verifica se a quantidade desejada está disponível no estoque
        if (estoque >= quantidade) {
            txtTotalDaVenda.setText(String.format("%.2f", total)); // Formata para 2 casas decimais

            // Adiciona ao carrinho
            meus_produtos = (DefaultTableModel) carrinho.getModel();
            meus_produtos.addRow(new Object[]{
                txtCodigo.getText(),
                TxtProduto.getText(),
                TxtQuantidade.getText(),
                String.format("%.2f", preco), // Formata o preço
                String.format("%.2f", subtotal) // Formata o subtotal
            });
        } else {
            JOptionPane.showMessageDialog(null, "A quantidade desejada é maior do que a disponível no estoque.");
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null, "Por favor, insira valores válidos nos campos de estoque, quantidade e preço.");
    }
} else {
    JOptionPane.showMessageDialog(null, "Não foi possível adicionar ao carrinho. Produto não encontrado ou falta de informações.");
}


    }//GEN-LAST:event_BtnAdicionar_ITEMActionPerformed

