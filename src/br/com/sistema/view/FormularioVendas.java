    private void BTNPAGAMENTOActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNPAGAMENTOActionPerformed
String nome = txtNome.getText();
if (nome == null || nome.trim().isEmpty()) {
    JOptionPane.showMessageDialog(null, "Por favor, insira o nome do cliente.");
    return; // Interrompe a execução se o nome estiver vazio
}

ClientesDao daoc = new ClientesDao();
clientes obj = daoc.BuscarCliente(nome);

if (obj != null && obj.getNome() != null) {
    // Cliente encontrado, segue o fluxo padrão
    FormularioPagamentos telaPag = new FormularioPagamentos(this,true);
    telaPag.clientes = obj;
    telaPag.meus_produtos = meus_produtos;  
    telaPag.txtNome.setText(obj.getNome()); // Define o nome do cliente no formulário
    telaPag.txtTotalPagar.setText(String.valueOf(total)); // Preenche o total no formulário
    telaPag.setVisible(true);
    this.dispose();
} else {
    // Cliente não encontrado, permite prosseguir sem registro
    int opcao = JOptionPane.showConfirmDialog(null,
        "Cliente não encontrado. Deseja prosseguir sem registrar o cliente?",
        "Novo Cliente",
        JOptionPane.YES_NO_OPTION);

    if (opcao == JOptionPane.YES_OPTION) {
        // Prossegue apenas com o nome do cliente
        FormularioPagamentos telaPag = new FormularioPagamentos(this,true);
        telaPag.nomeCliente = nome; // Salva apenas o nome do cliente na venda
        telaPag.meus_produtos = meus_produtos;
        telaPag.txtNome.setText(nome); // Define o nome no formulário
        telaPag.txtTotalPagar.setText(String.valueOf(total)); // Preenche o total no formulário
        telaPag.setVisible(true);
        this.dispose();
    } else {
        JOptionPane.showMessageDialog(null, "Operação cancelada. Por favor, registre o cliente.");
    }
}




    }//GEN-LAST:event_BTNPAGAMENTOActionPerformed

