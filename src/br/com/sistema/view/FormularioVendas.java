     public void listar() {
        ProdutosDAO dao = new ProdutosDAO();
        List<Produtos> lista = dao.lista();

        // Obtém o modelo da tabela e limpa as linhas existentes
        DefaultTableModel dados = (DefaultTableModel) Tabelaproduto.getModel();
        dados.setRowCount(0); // Limpa as linhas

        // Adiciona cada cliente como uma nova linha na tabela
        for (Produtos c : lista) {
            dados.addRow(new Object[] {
                c.getId(),          // id
                c.getNome(),        // nome
                c.getPreco(),      
                c.getEstoque()
            });
        }

    }
    
