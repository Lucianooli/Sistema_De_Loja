    private void btnPesquisarNomeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarNomeActionPerformed

        String nome = "%"+txtPesquisarNome.getText()+"%";
        
        
        ClientesDao dao = new ClientesDao();
        List<clientes> lista = dao.filtrar(nome);

        // Obtém o modelo da tabela e limpa as linhas existentes
        DefaultTableModel dados = (DefaultTableModel) tabela.getModel();
        dados.setRowCount(0); // Limpa as linhas

        // Adiciona cada cliente como uma nova linha na tabela
        for (clientes c : lista) {
            dados.addRow(new Object[]{
                c.getId(),
                c.getNome(),
                c.getEmail(),
                c.getCelular(),
                c.getTelefone(),
                c.getCep(),
                c.getEndereço(), // Nome do método corrigido
                c.getBairro(),
                c.getCidade(),
                c.getComplemento(),
                c.getSituacao(),
                c.getModelo(),
                c.getDescricao()
            });
        }

    }//GEN-LAST:event_btnPesquisarNomeActionPerformed

