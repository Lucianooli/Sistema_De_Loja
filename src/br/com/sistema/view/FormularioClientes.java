    private void BtnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEditarActionPerformed
    clientes obj = new clientes();

    // Configurar os valores a partir dos campos de texto
    obj.setId(Integer.parseInt(txtcodigo.getText())); // Adiciona o ID do cliente
    obj.setNome(txtnome.getText());
    obj.setEmail(txtEmail.getText());
    obj.setCelular(txtcelular.getText());
    obj.setTelefone(txtTelefone.getText());
    obj.setCep(txtCep.getText());
    obj.setEndereço(txtEndereço.getText());
    obj.setBairro(txtBairro.getText());
    obj.setCidade(txtCidade.getText());
    obj.setComplemento(txtComplemento.getText());
    obj.setModelo(txtmodelo.getText());

    // Configurar a situação a partir do combobox
    String situacaoSelecionada = (String) cbSituacao.getSelectedItem();
    obj.setSituacao(situacaoSelecionada);

    // Configurar a descrição
    obj.setDescricao(txtDescricao.getText());

    // Chamar o DAO para editar o cliente
    ClientesDao dao = new ClientesDao();
    dao.Editar(obj);

    // Limpar os campos após a edição
    Utilitarios novo = new Utilitarios();
    novo.LimpaTela(painel_dados_pessoais);

        

    }//GEN-LAST:event_BtnEditarActionPerformed

