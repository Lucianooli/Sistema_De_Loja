    private void bntremoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntremoverActionPerformed
try {
    // Obtem os valores dos campos
    int idProduto = Integer.parseInt(txtcodigo.getText());
    int qtdAtual = Integer.parseInt(txtQuantidadeAtual.getText());
    int qtdNova = Integer.parseInt(txtRemove.getText());

    // Calcula a nova quantidade
    int qtdAtualizada = qtdAtual - qtdNova;

    // Atualiza o estoque no banco de dados
    ProdutosDAO daop = new ProdutosDAO();
    daop.AdicionarEstoque(idProduto, qtdAtualizada);

    JOptionPane.showMessageDialog(null, "Removido com sucesso ao estoque!");
    new Utilitarios().LimpaTela(painel_dados_pessoais);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(null, "Erro: Insira apenas números nos campos. " + e.getMessage());
} catch (Exception e) {
    JOptionPane.showMessageDialog(null, "Erro: " + e.getMessage());
}    }//GEN-LAST:event_bntremoverActionPerformed

