    private void txtQuantidadeAtualActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtQuantidadeAtualActionPerformed
    try {
            String precoTexto = txtQuantidadeAtual.getText();

            // Impedir valores vazios
            if (precoTexto.isEmpty()) {
                JOptionPane.showMessageDialog(null, "O campo de preço não pode estar vazio.");
                return;
            }

            // Verificar se o valor é válido como número decimal
            double preco = Double.parseDouble(precoTexto);

            // Impedir valores negativos ou zero
            if (preco <= 0) {
                JOptionPane.showMessageDialog(null, "O preço deve ser maior que zero.");
                txtQuantidadeAtual.requestFocus();
            } else {
                JOptionPane.showMessageDialog(null, "Preço válido: " + preco);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Digite um valor numérico válido.");
            txtQuantidadeAtual.requestFocus();
        }
    }//GEN-LAST:event_txtQuantidadeAtualActionPerformed

    private void txtQuantidadeAtualKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtQuantidadeAtualKeyTyped
char c = evt.getKeyChar();

// Permitir apenas números e ponto decimal
if (!Character.isDigit(c) && c != ',') {
    evt.consume(); // Impede caracteres inválidos
}

// Impedir múltiplos pontos decimais
if (c == '.' && txtQuantidadeAtual.getText().contains(".")) {
    evt.consume(); // Apenas um ponto é permitido
}
    }//GEN-LAST:event_txtQuantidadeAtualKeyTyped

